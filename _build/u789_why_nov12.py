def norm(t):
    return re.sub(r'\s+', ' ', html.unescape(re.sub(r'<[^>]+>', '', t))).strip()


PAGES = ['unit7-practice', 'unit7-practice-1', 'unit7-practice-2', 'unit8-practice', 'unit8-practice-1', 'unit8-practice-2', 'unit9-practice']
ALL = {}
for items in N.values():
    for q, nt in items.items(): ALL[q] = {norm(k): v for k, v in nt.items()}
total, seen = 0, set()
for page in PAGES:
    p = os.path.join(ROOT, page + '.html'); s = open(p, encoding='utf-8').read()
    s = re.sub(r' data-why="[^"]*" data-why-by="u789"', '', s)   # rerun-safe
    for qid, notes in ALL.items():
        if "mc(this, '%s'" % qid not in s and "mc(this,'%s'" % qid not in s: continue
        done = set()
        def add(m):
            tag, text = m.group(1), m.group(2)
            if "'" + qid + "'" not in tag: return m.group(0)
            t = norm(text)
            if 'data-why=' in tag: done.add(t); return m.group(0)   # the page already has its own note
            if t in notes:
                done.add(t)
                return tag[:-1] + ' data-why="%s" data-why-by="u789">' % html.escape(notes[t], quote=True) + text
            return m.group(0)
        s = re.sub(r'(<button[^>]*onclick="mc\(this,\s*\'[^\']+\'[^>]*>)(.*?)(?=</button>)', add, s, flags=re.S)
        missing = set(notes) - done
        assert not missing, (page, qid, missing)
        total += len(done); seen.add(qid)
    open(p, 'w', encoding='utf-8').write(s)
assert seen == set(ALL), set(ALL) - seen
print('notes written:', total)
