def check_math():
    from fractions import Fraction as F
    def ev(s):
        s = s.replace('−', '-').replace('×', '*').replace('÷', '/').replace('²', '**2').replace('³', '**3')
        return eval(s, {'__builtins__': {}})
    for name in ('integers', 'expressions', 'multiply', 'add-subtract'):
        for q in QUIZ[name][1]:
            p = q[0].rstrip(' =')
            if ',' in p and name == 'expressions':
                expr, *vals = [t.strip() for t in p.split(',')]
                env = {}
                for v in vals: k, x = v.split('='); env[k.strip()] = int(x)
                expr = re.sub(r'(\d)([a-z])', r'\1*\2', expr)
                got = eval(expr.replace('−', '-'), {'__builtins__': {}}, env)
            else:
                got = ev(p)
            want = float(q[1][q[2]].replace('−', '-').replace(',', ''))
            assert abs(got - want) < 1e-9, (name, q[0], got, want)
    for q in QUIZ['divide'][1]:
        a, b = [int(x) for x in q[0].rstrip(' =').split(' ÷ ')]
        want = f'{a // b}' + (f' r {a % b}' if a % b else '')
        assert q[1][q[2]] == want, (q, want)
    print('math checks OK')

check_math()

